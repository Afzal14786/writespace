import logger from "@config/logger";
import env from "@config/env";
import { AppError } from "@shared/utils/app.error";
import { HTTP_STATUS } from "@shared/constants/http-codes";

import { db, type DatabaseTransaction } from "../../../db";

import { eventPublisherService } from "@modules/notification/services/event-publisher.service";

import type {
  FollowResult,
  FollowUserInput,
  UnfollowUserInput,
} from "../contracts/follow.types";

import { interactionEventMapper } from "../events/interaction-event.mapper";
import { interactionEventPublisher } from "../events/interaction-event.publisher";

import { followRepository } from "../repositories/follow.repository";

/**
 * Domain events generated by follow relationship changes.
 *
 * Both events use the same payload contract, but represent different
 * business facts and are interpreted separately by the notification system.
 */
type FollowDomainEventName = "follow.created" | "follow.removed";

export class FollowService {
  /**
   * Verifies that the target account exists before modifying
   * the follow relationship.
   */
  private async ensureTargetUserExists(targetUserId: string): Promise<void> {
    const exists = await followRepository.userExists(targetUserId);

    if (!exists) {
      throw new AppError(HTTP_STATUS.NOT_FOUND, "User not found");
    }
  }

  /**
   * Persist the domain event in the same transaction as the follow
   * relationship and user-counter changes.
   *
   * The outbox row is durable even when background processing is disabled.
   * A later dispatcher can process the pending event without losing it.
   */
  private async recordFollowDomainEvent(
    transaction: DatabaseTransaction,
    eventName: FollowDomainEventName,
    actorId: string,
    targetUserId: string,
  ): Promise<void> {
    // Do not record notification events while the outbox pipeline is disabled.
    if (!env.OUTBOX_PROCESSING_ENABLED) {
      return;
    }

    await eventPublisherService.recordInTransaction(transaction, {
      eventName,
      producer: "interactions.follow",
      actorId,

      aggregate: {
        type: "FOLLOW_RELATIONSHIP",
        id: `${actorId}:${targetUserId}`,
      },

      payload: {
        targetUserId,
      },
    });
  }

  /**
   * Handle post-commit follow-created side effects.
   *
   * The user-facing notification is produced exclusively through the
   * durable outbox pipeline. Interaction history remains a separate,
   * best-effort operation.
   */
  private async handleFollowCreated(
    actorId: string,
    targetUserId: string,
  ): Promise<void> {
    try {
      const event = interactionEventMapper.mapFollowEvent("follow.created", {
        actorId,
        targetUserId,
      });

      await interactionEventPublisher.publish(event);
    } catch (error) {
      logger.error("Failed to publish follow.created interaction event", {
        actorId,
        targetUserId,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }

  /**
   * Records the removal of a follow relationship after the transaction
   * has committed.
   */
  private async handleFollowRemoved(
    actorId: string,
    targetUserId: string,
  ): Promise<void> {
    try {
      const event = interactionEventMapper.mapFollowEvent("follow.removed", {
        actorId,
        targetUserId,
      });

      await interactionEventPublisher.publish(event);
    } catch (error) {
      logger.error("Failed to publish follow.removed interaction event", {
        actorId,
        targetUserId,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }

  /**
   * Explicit follow operation.
   *
   * The relationship, user counters and outbox event are committed
   * atomically.
   */
  async followUser(input: FollowUserInput): Promise<FollowResult> {
    const { actorId, targetUserId } = input;

    if (actorId === targetUserId) {
      throw new AppError(HTTP_STATUS.BAD_REQUEST, "You cannot follow yourself");
    }

    await this.ensureTargetUserExists(targetUserId);

    const follow = await db.transaction(async (transaction) => {
      const createdFollow = await followRepository.createFollow(
        transaction,
        actorId,
        targetUserId,
      );

      /*
       * Idempotent operation:
       * the user was already following the target.
       *
       * No state changed, so no domain event or notification is generated.
       */
      if (!createdFollow) {
        return null;
      }

      await this.recordFollowDomainEvent(
        transaction,
        "follow.created",
        actorId,
        targetUserId,
      );

      return createdFollow;
    });

    if (!follow) {
      return {
        followerId: actorId,
        followingId: targetUserId,
        isFollowing: true,
      };
    }

    // Interaction history is published only after the main transaction commits.
    await this.handleFollowCreated(actorId, targetUserId);

    return {
      followerId: follow.followerId,
      followingId: follow.followingId,
      isFollowing: true,
    };
  }

  /**
   * Explicit unfollow operation.
   *
   * The relationship deletion, counter changes and corresponding outbox
   * event are committed atomically.
   */
  async unfollowUser(input: UnfollowUserInput): Promise<FollowResult> {
    const { actorId, targetUserId } = input;

    if (actorId === targetUserId) {
      throw new AppError(
        HTTP_STATUS.BAD_REQUEST,
        "You cannot unfollow yourself",
      );
    }

    await this.ensureTargetUserExists(targetUserId);

    const follow = await db.transaction(async (transaction) => {
      const deletedFollow = await followRepository.deleteFollow(
        transaction,
        actorId,
        targetUserId,
      );

      /*
       * No existing relationship means no state changed.
       * Therefore, no follow.removed event is recorded.
       */
      if (!deletedFollow) {
        return null;
      }

      await this.recordFollowDomainEvent(
        transaction,
        "follow.removed",
        actorId,
        targetUserId,
      );

      return deletedFollow;
    });

    if (!follow) {
      return {
        followerId: actorId,
        followingId: targetUserId,
        isFollowing: false,
      };
    }

    await this.handleFollowRemoved(actorId, targetUserId);

    return {
      followerId: follow.followerId,
      followingId: follow.followingId,
      isFollowing: false,
    };
  }

  /**
   * Backward compatibility for the old POST /users/:id/follow endpoint.
   *
   * New API clients should use the explicit follow and unfollow endpoints.
   * The relationship change, counter updates and matching outbox event
   * share a single transaction.
   */
  async toggleFollow(
    input: FollowUserInput,
  ): Promise<{ status: "followed" | "unfollowed" }> {
    const { actorId, targetUserId } = input;

    if (actorId === targetUserId) {
      throw new AppError(HTTP_STATUS.BAD_REQUEST, "You cannot follow yourself");
    }

    await this.ensureTargetUserExists(targetUserId);

    const result = await db.transaction(async (transaction) => {
      const toggleResult = await followRepository.toggleFollow(
        transaction,
        actorId,
        targetUserId,
      );

      /*
       * A conflicting writer may have changed nothing through this
       * operation. Do not generate a domain event for an unchanged state.
       */
      if (!toggleResult.changed) {
        return toggleResult;
      }

      await this.recordFollowDomainEvent(
        transaction,
        toggleResult.isFollowing ? "follow.created" : "follow.removed",
        actorId,
        targetUserId,
      );

      return toggleResult;
    });

    if (!result.changed) {
      return {
        status: result.isFollowing ? "followed" : "unfollowed",
      };
    }

    if (result.isFollowing) {
      await this.handleFollowCreated(actorId, targetUserId);

      return { status: "followed" };
    }

    await this.handleFollowRemoved(actorId, targetUserId);

    return { status: "unfollowed" };
  }

  /**
   * Check whether one user follows another.
   */
  async isFollowing(followerId: string, followingId: string): Promise<boolean> {
    return followRepository.isFollowing(followerId, followingId);
  }
}

export const followService = new FollowService();
