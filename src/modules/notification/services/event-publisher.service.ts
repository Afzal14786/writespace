import { ZodError, z } from "zod";

import type { DatabaseTransaction } from "../../../db";

import type {
  NewOutboxEvent,
  OutboxEvent,
} from "../../../db/schema/outbox-events";

import { HTTP_STATUS } from "@shared/constants/http-codes";
import { AppError } from "@shared/utils/app.error";

import type { DomainEventInput } from "../contracts/event-envelope.types";
import type { DomainEventName } from "../domain/event-name";

import {
  getEventVersion,
  parseEventPayload,
  type EventPayloadMap,
} from "../events/event.registry";

import { outboxRepository } from "../repositories/outbox.repository";

/**
 * Validates fields shared by all domain events.
 *
 * These checks provide clear application errors before invalid values
 * reach PostgreSQL and produce less useful database-level errors.
 */
function validateCommonEventFields(
  input: DomainEventInput<DomainEventName, unknown>,
): void {
  if (
    typeof input.producer !== "string" ||
    input.producer.trim().length === 0
  ) {
    throw new AppError(
      HTTP_STATUS.UNPROCESSABLE_ENTITY,
      "Event producer must not be empty.",
    );
  }

  if (
    input.occurredAt !== undefined &&
    (!(input.occurredAt instanceof Date) ||
      Number.isNaN(input.occurredAt.getTime()))
  ) {
    throw new AppError(
      HTTP_STATUS.UNPROCESSABLE_ENTITY,
      "Event occurredAt must be a valid Date.",
    );
  }

  if (input.actorId !== undefined && input.actorId !== null) {
    const actorIdResult = z.string().uuid().safeParse(input.actorId);

    if (!actorIdResult.success) {
      throw new AppError(
        HTTP_STATUS.UNPROCESSABLE_ENTITY,
        "Event actorId must be a valid UUID.",
      );
    }
  }

  if (input.aggregate !== undefined && input.aggregate !== null) {
    if (
      typeof input.aggregate.type !== "string" ||
      input.aggregate.type.trim().length === 0 ||
      typeof input.aggregate.id !== "string" ||
      input.aggregate.id.trim().length === 0
    ) {
      throw new AppError(
        HTTP_STATUS.UNPROCESSABLE_ENTITY,
        "Event aggregate type and ID must not be empty.",
      );
    }
  }

  if (
    input.metadata !== undefined &&
    (typeof input.metadata !== "object" ||
      input.metadata === null ||
      Array.isArray(input.metadata))
  ) {
    throw new AppError(
      HTTP_STATUS.UNPROCESSABLE_ENTITY,
      "Event metadata must be a valid object.",
    );
  }
}

/**
 * Records domain events in PostgreSQL's transactional outbox.
 *
 * Important:
 * - This service does not create or commit a transaction.
 * - The caller must pass the transaction used by the business operation.
 * - The event payload is validated against its registered schema/version.
 * - The returned row contains the stable event ID generated by PostgreSQL.
 *
 * This service does NOT publish to BullMQ. The outbox dispatcher handles
 * queue publication using the persisted event ID.
 */
export class EventPublisherService {
  /**
   * Validate and persist a domain event using the caller's transaction.
   *
   * Example:
   *
   * await db.transaction(async (tx) => {
   *   // 1. Apply the business operation using tx.
   *   // 2. Record the corresponding event using this service and tx.
   * });
   */
  public async recordInTransaction<TName extends DomainEventName>(
    transaction: DatabaseTransaction,
    input: DomainEventInput<TName, EventPayloadMap[TName]>,
  ): Promise<OutboxEvent> {
    validateCommonEventFields(
      input as DomainEventInput<DomainEventName, unknown>,
    );

    // When callers omit a version, use the version currently registered
    // for the event. Unsupported explicit versions are rejected below.
    const eventVersion = input.eventVersion ?? getEventVersion(input.eventName);

    let validatedPayload: EventPayloadMap[TName];

    try {
      validatedPayload = parseEventPayload(
        input.eventName,
        eventVersion,
        input.payload,
      );
    } catch (error) {
      // Invalid payloads are permanent application/data errors.
      // Preserve AppError from the registry (for example, unsupported
      // event versions) instead of wrapping it again.
      if (error instanceof AppError) {
        throw error;
      }

      if (error instanceof ZodError) {
        const invalidFields = error.issues
          .map((issue) => issue.path.join(".") || "(payload)")
          .join(", ");

        throw new AppError(
          HTTP_STATUS.UNPROCESSABLE_ENTITY,
          `Invalid payload for event "${input.eventName}". ` +
            `Check these fields: ${invalidFields}.`,
        );
      }

      // Unexpected errors should retain their original identity.
      throw error;
    }

    const outboxInput: NewOutboxEvent = {
      eventName: input.eventName,
      eventVersion,
      producer: input.producer.trim(),

      actorId: input.actorId ?? null,

      aggregateType: input.aggregate?.type ?? null,
      aggregateId: input.aggregate?.id ?? null,

      correlationId: input.correlationId ?? null,
      causationId: input.causationId ?? null,

      payload: validatedPayload as Record<string, unknown>,
      metadata: input.metadata ?? {},

      // Leave occurredAt out when omitted so PostgreSQL applies the
      // outbox table's default timestamp.
      ...(input.occurredAt ? { occurredAt: input.occurredAt } : {}),
    };

    return outboxRepository.create(transaction, outboxInput);
  }
}

export const eventPublisherService = new EventPublisherService();
